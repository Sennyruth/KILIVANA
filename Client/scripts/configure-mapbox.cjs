const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const localConfigPath = path.join(projectRoot, '.env.local');
const generatedConfigPath = path.join(projectRoot, 'src/environments/mapbox-token.generated.ts');
let localToken = '';

if (fs.existsSync(localConfigPath)) {
  const localConfig = fs.readFileSync(localConfigPath, 'utf8');
  const match = localConfig.match(/^\s*MAPBOX_ACCESS_TOKEN\s*=\s*(.*?)\s*$/m);
  localToken = match?.[1] ?? '';
}

const token = process.env.MAPBOX_ACCESS_TOKEN?.trim() || localToken.trim();
fs.writeFileSync(
  generatedConfigPath,
  `// Generated by scripts/configure-mapbox.cjs. Do not commit this file.\nexport const MAPBOX_ACCESS_TOKEN = ${JSON.stringify(token)};\n`,
  'utf8',
);

if (!token) {
  process.stdout.write('Mapbox token is not configured; the live map will show its setup message.\n');
}
